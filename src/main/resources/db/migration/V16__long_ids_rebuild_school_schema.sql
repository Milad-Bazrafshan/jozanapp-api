-- Rebuild school schema with BIGINT surrogate keys (per-table IDENTITY / sequence).
-- Destroys all data in schema school — intended for dev/test resets per product request.

DROP SCHEMA IF EXISTS school CASCADE;
CREATE SCHEMA school;
CREATE TABLE school.tenant (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(80) NOT NULL,
    name VARCHAR(200) NOT NULL,
    status VARCHAR(30) NOT NULL,
    timezone VARCHAR(80) NOT NULL DEFAULT 'Asia/Tehran',
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    course_selection_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    virtual_class_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    sms_provider VARCHAR(40) NOT NULL DEFAULT 'DEMO',
    meeting_provider VARCHAR(40) NOT NULL DEFAULT 'GENERIC_LINK',
    meeting_base_url VARCHAR(400),
    meeting_secret VARCHAR(400),
    CONSTRAINT uq_tenant_slug UNIQUE (slug),
    CONSTRAINT ck_tenant_slug_lowercase CHECK (slug = lower(slug))
);

CREATE TABLE school.educational_institution (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES school.tenant(id),
    name VARCHAR(200) NOT NULL,
    institution_type VARCHAR(40) NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_institution_tenant UNIQUE (tenant_id),
    CONSTRAINT uq_institution_tenant_id UNIQUE (tenant_id, id)
);

CREATE TABLE school.branch (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES school.tenant(id),
    institution_id BIGINT NOT NULL REFERENCES school.educational_institution(id),
    code VARCHAR(40) NOT NULL,
    name VARCHAR(200) NOT NULL,
    status VARCHAR(30) NOT NULL,
    phone VARCHAR(30),
    address VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_branch_tenant_code UNIQUE (tenant_id, code),
    CONSTRAINT uq_branch_tenant_id UNIQUE (tenant_id, id)
);

CREATE TABLE school.user_account (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(30) NOT NULL,
    password_changed_at TIMESTAMPTZ NOT NULL,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    two_factor_sms_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_user_account_email UNIQUE (email),
    CONSTRAINT ck_user_account_email_lowercase CHECK (email = lower(email))
);

CREATE TABLE school.two_factor_sms_challenge (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES school.user_account(id),
    purpose VARCHAR(30) NOT NULL,
    code_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX ix_two_factor_sms_challenge_account ON school.two_factor_sms_challenge(account_id)
    WHERE consumed = FALSE;

CREATE TABLE school.person (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES school.tenant(id),
    first_name VARCHAR(120) NOT NULL,
    last_name VARCHAR(120) NOT NULL,
    national_id VARCHAR(30),
    mobile VARCHAR(30),
    date_of_birth DATE,
    fathers_name VARCHAR(120),
    place_of_birth VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_person_tenant_id UNIQUE (tenant_id, id)
);

CREATE UNIQUE INDEX uq_person_tenant_national_id
    ON school.person (tenant_id, national_id)
    WHERE national_id IS NOT NULL;

CREATE TABLE school.tenant_membership (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES school.tenant(id),
    user_account_id BIGINT NOT NULL REFERENCES school.user_account(id),
    person_id BIGINT NOT NULL REFERENCES school.person(id),
    status VARCHAR(30) NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_membership_tenant_user UNIQUE (tenant_id, user_account_id),
    CONSTRAINT uq_membership_tenant_person UNIQUE (tenant_id, person_id)
);

CREATE TABLE school.permission (
    code VARCHAR(100) PRIMARY KEY,
    module VARCHAR(60) NOT NULL,
    description VARCHAR(250) NOT NULL
);

CREATE TABLE school.access_role (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES school.tenant(id),
    code VARCHAR(60) NOT NULL,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    system_role BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_role_tenant_code UNIQUE (tenant_id, code),
    CONSTRAINT uq_role_tenant_id UNIQUE (tenant_id, id)
);

CREATE TABLE school.role_permission (
    role_id BIGINT NOT NULL REFERENCES school.access_role(id) ON DELETE CASCADE,
    permission_code VARCHAR(100) NOT NULL REFERENCES school.permission(code),
    PRIMARY KEY (role_id, permission_code)
);

CREATE TABLE school.access_grant (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES school.tenant(id),
    membership_id BIGINT NOT NULL REFERENCES school.tenant_membership(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES school.access_role(id),
    scope_type VARCHAR(30) NOT NULL,
    scope_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL,
    created_by BIGINT REFERENCES school.user_account(id),
    CONSTRAINT ck_access_grant_scope CHECK (
        (scope_type = 'TENANT' AND scope_id IS NULL)
        OR (scope_type = 'BRANCH' AND scope_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_access_grant
    ON school.access_grant (membership_id, role_id, scope_type, COALESCE(scope_id, 0));

CREATE TABLE school.refresh_token (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash CHAR(64) NOT NULL,
    user_account_id BIGINT NOT NULL REFERENCES school.user_account(id),
    membership_id BIGINT NOT NULL REFERENCES school.tenant_membership(id),
    tenant_id BIGINT NOT NULL REFERENCES school.tenant(id),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    replaced_by_id BIGINT REFERENCES school.refresh_token(id),
    CONSTRAINT uq_refresh_token_hash UNIQUE (token_hash)
);

CREATE INDEX ix_refresh_token_membership ON school.refresh_token (membership_id, expires_at);

CREATE TABLE school.password_reset_token (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash CHAR(64) NOT NULL,
    user_account_id BIGINT NOT NULL REFERENCES school.user_account(id),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    CONSTRAINT uq_password_reset_token_hash UNIQUE (token_hash)
);

CREATE TABLE school.external_identity (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_account_id BIGINT NOT NULL REFERENCES school.user_account(id),
    provider VARCHAR(60) NOT NULL,
    external_user_id VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_external_identity_provider_user UNIQUE (provider, external_user_id),
    CONSTRAINT uq_external_identity_account_provider UNIQUE (user_account_id, provider)
);

CREATE TABLE school.audit_log (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT REFERENCES school.tenant(id),
    actor_user_id BIGINT REFERENCES school.user_account(id),
    action VARCHAR(100) NOT NULL,
    resource_type VARCHAR(100) NOT NULL,
    resource_id BIGINT,
    trace_id VARCHAR(128),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX ix_audit_log_tenant_occurred_at ON school.audit_log (tenant_id, occurred_at DESC);

